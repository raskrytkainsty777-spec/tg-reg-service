export type NameLists = {
  gender: string;
  femaleFirstNames: string[];
  femaleLastNames: string[];
  maleFirstNames: string[];
  maleLastNames: string[];
};

const orDefault = (items: string[] | undefined, fallback: string[]) =>
  items && items.length ? items : fallback;

export const generateAccountProfile = (lists?: NameLists) => {
  // Пол: из настроек, «вперемешку» — монеткой на каждый аккаунт
  const gender = lists?.gender === "mixed" ? (Math.random() < 0.5 ? "female" : "male") : lists?.gender;
  const male = gender === "male";
  const firstName = randomItem(
    male
      ? orDefault(lists?.maleFirstNames, MALE_FIRST_NAMES)
      : orDefault(lists?.femaleFirstNames, FEMALE_FIRST_NAMES),
  );
  const lastName = randomItem(
    male
      ? orDefault(lists?.maleLastNames, MALE_LAST_NAMES)
      : orDefault(lists?.femaleLastNames, FEMALE_LAST_NAMES),
  );
  const suffix = randomInt(1000, 9999);
  const currentYear = new Date().getUTCFullYear();
  const birthYear = randomInt(1985, currentYear - 19);
  const birthMonth = randomInt(1, 12);
  const birthDay = randomInt(1, 28);

  return {
    firstName,
    lastName,
    username: `${toLatin(firstName)}_${toLatin(lastName)}_${suffix}`,
    birthDate: new Date(Date.UTC(birthYear, birthMonth - 1, birthDay)),
    twoFaPassword: `Safe${suffix}!${randomInt(10, 99)}`,
  };
};

